"""Industrial Sensor Simulator Module.

Generates realistic time-series sensor data for industrial process monitoring:
1. Temperature Sensor (°C)
2. Pressure Sensor (kPa)
3. Liquid Level Sensor (%)

Features configurable sample size, reproducible random seeds, normal operating
dynamics, and multiple synthetic fault injection modes.

DISCLAIMER: All data generated by this module is SIMULATED for educational and
testing purposes and does NOT represent live physical industrial instrumentation.
"""

from __future__ import annotations

import datetime
from dataclasses import dataclass
from typing import Any, Dict, List, Optional
import numpy as np
import pandas as pd


@dataclass
class SensorConfig:
    """Configuration parameters for an individual sensor."""

    sensor_id: str
    measurement_type: str
    unit: str
    nominal_mean: float
    nominal_std: float
    min_physical_limit: float
    max_physical_limit: float
    default_lower_threshold: float
    default_upper_threshold: float


# Standard factory default specifications for the three industrial sensors
DEFAULT_SENSOR_CONFIGS: Dict[str, SensorConfig] = {
    "TEMP_001": SensorConfig(
        sensor_id="TEMP_001",
        measurement_type="temperature",
        unit="°C",
        nominal_mean=70.0,
        nominal_std=2.0,
        min_physical_limit=-50.0,
        max_physical_limit=300.0,
        default_lower_threshold=50.0,
        default_upper_threshold=90.0,
    ),
    "PRES_001": SensorConfig(
        sensor_id="PRES_001",
        measurement_type="pressure",
        unit="kPa",
        nominal_mean=150.0,
        nominal_std=4.0,
        min_physical_limit=0.0,
        max_physical_limit=500.0,
        default_lower_threshold=120.0,
        default_upper_threshold=180.0,
    ),
    "LVL_001": SensorConfig(
        sensor_id="LVL_001",
        measurement_type="level",
        unit="%",
        nominal_mean=55.0,
        nominal_std=3.0,
        min_physical_limit=0.0,
        max_physical_limit=100.0,
        default_lower_threshold=20.0,
        default_upper_threshold=80.0,
    ),
}

FAULT_MODES = [
    "None (Normal)",
    "High Spike",
    "Low Drop",
    "Sensor Drift",
    "Missing Data",
    "Invalid Reading",
    "Random Mixed Faults",
]


class SensorSimulator:
    """Simulates industrial time-series sensor telemetry with realistic dynamics.

    Provides reproducible stochastic sensor signals with optional deterministic
    or probabilistic fault injection.
    """

    def __init__(
        self,
        configs: Optional[Dict[str, SensorConfig]] = None,
        seed: Optional[int] = None,
    ) -> None:
        """Initialize the simulator with sensor configurations and random seed.

        Args:
            configs: Mapping of sensor_id to SensorConfig. Defaults to DEFAULT_SENSOR_CONFIGS.
            seed: Optional integer seed for reproducible pseudorandom sequences.
        """
        self.configs = configs if configs is not None else DEFAULT_SENSOR_CONFIGS.copy()
        self.seed = seed
        self.rng = np.random.default_rng(seed)

    def set_seed(self, seed: Optional[int]) -> None:
        """Reset the random number generator seed.

        Args:
            seed: Integer seed or None.
        """
        self.seed = seed
        self.rng = np.random.default_rng(seed)

    def generate_time_series(
        self,
        count: int = 100,
        interval_seconds: int = 5,
        start_time: Optional[datetime.datetime] = None,
        fault_type: str = "None (Normal)",
        fault_rate: float = 0.1,
        seed: Optional[int] = None,
    ) -> pd.DataFrame:
        """Generate time-series readings for all configured sensors.

        Args:
            count: Number of timestamps to generate per sensor (must be >= 1).
            interval_seconds: Time interval between consecutive samples in seconds.
            start_time: Starting timestamp. If None, uses current UTC time minus elapsed.
            fault_type: Fault mode selected from FAULT_MODES.
            fault_rate: Probability of fault occurrence per sample (0.0 to 1.0).
            seed: Optional seed override for this run.

        Returns:
            pd.DataFrame with columns:
                ['timestamp', 'sensor_id', 'measurement_type', 'reading_value',
                 'unit', 'is_simulated', 'injected_fault']

        Raises:
            ValueError: If count < 1, interval_seconds < 1, or fault_rate not in [0, 1].
        """
        if count < 1:
            raise ValueError(f"Count must be a positive integer, received: {count}")
        if interval_seconds < 1:
            raise ValueError(
                f"Interval seconds must be >= 1, received: {interval_seconds}"
            )
        if not (0.0 <= fault_rate <= 1.0):
            raise ValueError(
                f"Fault rate must be between 0.0 and 1.0, received: {fault_rate}"
            )

        if seed is not None:
            self.set_seed(seed)

        if start_time is None:
            total_duration = datetime.timedelta(seconds=(count - 1) * interval_seconds)
            start_time = datetime.datetime.now(datetime.timezone.utc) - total_duration

        records: List[Dict[str, Any]] = []

        # Generate timestamps
        timestamps = [
            start_time + datetime.timedelta(seconds=i * interval_seconds)
            for i in range(count)
        ]

        # Generate time series for each sensor
        for sensor_id, cfg in self.configs.items():
            # Base normal signal: mean + stationary Gaussian noise + slight sinusoidal process wave
            time_indices = np.arange(count)
            # Subtle low-frequency process fluctuation (simulates physical plant cycle)
            cycle_phase = self.rng.uniform(0, 2 * np.pi)
            process_oscillation = 0.5 * cfg.nominal_std * np.sin(
                2 * np.pi * time_indices / max(count // 3, 10) + cycle_phase
            )
            gaussian_noise = self.rng.normal(0, cfg.nominal_std, size=count)
            base_values = cfg.nominal_mean + process_oscillation + gaussian_noise

            for i, ts in enumerate(timestamps):
                raw_val = float(base_values[i])
                injected = "None"
                final_val: Optional[float] = raw_val

                # Determine if a fault should be injected at this timestamp
                should_fault = self.rng.random() < fault_rate

                if fault_type == "High Spike" and should_fault:
                    # Exceed upper threshold significantly
                    spike_magnitude = (
                        cfg.default_upper_threshold - cfg.nominal_mean
                    ) * self.rng.uniform(1.2, 1.8)
                    final_val = cfg.nominal_mean + spike_magnitude
                    injected = "High Spike"

                elif fault_type == "Low Drop" and should_fault:
                    # Drop below lower threshold significantly
                    drop_magnitude = (
                        cfg.nominal_mean - cfg.default_lower_threshold
                    ) * self.rng.uniform(1.2, 1.8)
                    final_val = max(cfg.nominal_mean - drop_magnitude, cfg.min_physical_limit)
                    injected = "Low Drop"

                elif fault_type == "Sensor Drift":
                    # Gradual progressive linear drift across the entire sequence
                    drift_factor = (i / count) * (
                        cfg.default_upper_threshold - cfg.nominal_mean
                    ) * 1.5
                    final_val = raw_val + drift_factor
                    if abs(final_val - cfg.nominal_mean) > (
                        cfg.default_upper_threshold - cfg.nominal_mean
                    ):
                        injected = "Sensor Drift"

                elif fault_type == "Missing Data" and should_fault:
                    final_val = np.nan
                    injected = "Missing Data"

                elif fault_type == "Invalid Reading" and should_fault:
                    # Injected invalid readings: physically out of range or uncalibrated
                    choice = self.rng.integers(0, 3)
                    if choice == 0:
                        final_val = cfg.max_physical_limit + self.rng.uniform(50.0, 150.0)
                    elif choice == 1:
                        final_val = cfg.min_physical_limit - self.rng.uniform(20.0, 50.0)
                    else:
                        final_val = np.nan
                    injected = "Invalid Reading"

                elif fault_type == "Random Mixed Faults" and should_fault:
                    mode = self.rng.choice(
                        ["High Spike", "Low Drop", "Missing Data", "Invalid Reading"]
                    )
                    if mode == "High Spike":
                        final_val = cfg.default_upper_threshold + self.rng.uniform(5.0, 25.0)
                        injected = "High Spike"
                    elif mode == "Low Drop":
                        final_val = cfg.default_lower_threshold - self.rng.uniform(5.0, 20.0)
                        injected = "Low Drop"
                    elif mode == "Missing Data":
                        final_val = np.nan
                        injected = "Missing Data"
                    elif mode == "Invalid Reading":
                        final_val = cfg.min_physical_limit - 30.0
                        injected = "Invalid Reading"

                # Round valid values to 2 decimal places for instrumentation realism
                if final_val is not None and not np.isnan(final_val):
                    final_val = round(float(final_val), 2)

                records.append(
                    {
                        "timestamp": ts.isoformat(),
                        "sensor_id": sensor_id,
                        "measurement_type": cfg.measurement_type,
                        "reading_value": final_val,
                        "unit": cfg.unit,
                        "is_simulated": True,
                        "injected_fault": injected,
                    }
                )

        df = pd.DataFrame(records)
        df["timestamp"] = pd.to_datetime(df["timestamp"])
        df = df.sort_values(by=["timestamp", "sensor_id"]).reset_index(drop=True)
        return df

    def generate_single_reading(
        self,
        sensor_id: str,
        timestamp: Optional[datetime.datetime] = None,
        fault_type: str = "None",
    ) -> Dict[str, Any]:
        """Generate a single real-time simulated telemetry record for a specific sensor.

        Args:
            sensor_id: Identifier of the sensor to query.
            timestamp: Optional specific timestamp.
            fault_type: Fault mode to apply.

        Returns:
            Dictionary matching the telemetry schema.
        """
        if sensor_id not in self.configs:
            raise KeyError(f"Sensor ID '{sensor_id}' not found in configuration.")

        cfg = self.configs[sensor_id]
        ts = timestamp or datetime.datetime.now(datetime.timezone.utc)
        val = float(self.rng.normal(cfg.nominal_mean, cfg.nominal_std))

        injected = "None"
        if fault_type == "High Spike":
            val = cfg.default_upper_threshold + float(self.rng.uniform(5.0, 20.0))
            injected = "High Spike"
        elif fault_type == "Low Drop":
            val = cfg.default_lower_threshold - float(self.rng.uniform(5.0, 15.0))
            injected = "Low Drop"
        elif fault_type == "Missing Data":
            val = np.nan
            injected = "Missing Data"
        elif fault_type == "Invalid Reading":
            val = cfg.min_physical_limit - 20.0
            injected = "Invalid Reading"

        if not np.isnan(val):
            val = round(val, 2)

        return {
            "timestamp": ts.isoformat(),
            "sensor_id": sensor_id,
            "measurement_type": cfg.measurement_type,
            "reading_value": val,
            "unit": cfg.unit,
            "is_simulated": True,
            "injected_fault": injected,
        }
